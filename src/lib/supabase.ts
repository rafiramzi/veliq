// Client Supabase OPSIONAL. Selama EXPO_PUBLIC_SUPABASE_URL / _ANON_KEY kosong,
// `supabase` bernilai null dan aplikasi berjalan sepenuhnya lokal.
import 'react-native-url-polyfill/auto';
import AsyncStorage from '@react-native-async-storage/async-storage';
import { createClient, SupabaseClient } from '@supabase/supabase-js';

const url = process.env.EXPO_PUBLIC_SUPABASE_URL ?? '';
const anonKey = process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY ?? '';

export const isSupabaseConfigured = url.startsWith('https://') && anonKey.length > 20;

export const supabase: SupabaseClient | null = isSupabaseConfigured
  ? createClient(url, anonKey, {
      auth: {
        storage: AsyncStorage,
        autoRefreshToken: true,
        persistSession: true,
        detectSessionInUrl: false,
      },
    })
  : null;

/** Nama bucket Storage privat untuk foto dokumen. */
export const DOCUMENT_BUCKET = 'documents';
